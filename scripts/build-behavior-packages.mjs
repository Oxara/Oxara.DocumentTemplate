import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {core,full,loadBehaviorPackage} from './behavior-packages.mjs';
const root=path.resolve(import.meta.dirname,'..');
const packages=JSON.parse(await readFile(path.join(root,'feature-packages/packages.json'),'utf8'));
const features=JSON.parse(await readFile(path.join(root,'features/features.json'),'utf8'));
for(const [name,files]of Object.entries({core,full})){
 // Package metadata owns membership; this manifest owns evaluation order.
 // Reject drift rather than silently omitting a newly declared behavior.
 const declared=packages[name].includes.flatMap(id=>features[id].js).map(file=>file.replace(/^features\//,''));
 if(new Set(files).size!==files.length||declared.length!==files.length||declared.some(file=>!files.includes(file)))throw Error('Behavior membership differs from package metadata: '+name);
 const initialized=new Set();
 for(const file of files){const id=Object.keys(features).find(id=>features[id].js.includes('features/'+file));for(const dependency of features[id].requires)if(features[dependency].js.length&&!initialized.has(dependency))throw Error('Behavior dependency order: '+id+' requires '+dependency);initialized.add(id);}
 const output=`// Generated by scripts/build-behavior-packages.mjs; edit the shared source there.\n(${loadBehaviorPackage.toString()})(${JSON.stringify('documentTemplate'+name[0].toUpperCase()+name.slice(1))},${JSON.stringify(files)});\n`;
 const file=path.join(root,'feature-packages',name+'.js');
 if(process.argv.includes('--check')){if(await readFile(file,'utf8')!==output)throw Error('Behavior package drift: '+name);}
 else await writeFile(file,output);
}
console.log('Behavior packages current');
