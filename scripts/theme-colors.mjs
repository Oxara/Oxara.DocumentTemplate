import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
export async function renderThemeColors(theme){
 for(const key of ['brand','brandLight','primaryBackground','primaryHover','primaryForeground','neutralInk','neutralGraphite','linkLight','linkHoverLight','focusLight'])if(!/^#[0-9A-F]{6}$/.test(theme[key]||''))throw Error('Invalid Brand theme role: '+key);
 const source=JSON.parse(await readFile(path.join(root,'features/base/theme-tokens.json'),'utf8'));
 const rgb=hex=>hex.slice(1).match(/../g).map(x=>parseInt(x,16)).join(', ');
 const blocks=['light','dark'].map(mode=>{
  const dark=mode==='dark',accent=rgb(theme.brand);
  const managed={
   'oxara-ink':theme.neutralInk,'oxara-graphite':theme.neutralGraphite,
   brand:theme.brand,'brand-light':theme.brandLight,
   'brand-subtle':`rgba(${accent}, ${dark?'.1':'.055'})`,'brand-border':`rgba(${accent}, ${dark?'.28':'.18'})`,
   'identity-accent':'var(--brand)','ui-primary':theme.primaryBackground,'ui-primary-hover':theme.primaryHover,'ui-primary-foreground':theme.primaryForeground,
   'ui-link':dark?theme.brand:theme.linkLight,'ui-link-hover':dark?theme.brandLight:theme.linkHoverLight,'ui-focus':dark?theme.brand:theme.focusLight,'ui-indicator':'var(--brand)',
   'page-start-gradient':`radial-gradient(ellipse at 50% 0%, rgba(${accent}, ${dark?'.18':'.1'}), transparent 62%), linear-gradient(180deg, ${dark?`rgba(${rgb(theme.neutralGraphite)}, .94)`:'rgba(245, 248, 250, .95)'}, transparent)`,
   'page-end-gradient':`radial-gradient(ellipse at 50% 100%, rgba(${accent}, ${dark?'.15':'.08'}), transparent 64%), linear-gradient(0deg, ${dark?`rgba(${rgb(theme.neutralGraphite)}, .94)`:'rgba(245, 248, 250, .95)'}, transparent)`
  };
  const values={...managed,...source[mode]};
  return `${dark?'[data-theme="dark"]':':root, [data-theme="light"]'} {\n${Object.entries(values).map(([key,value])=>`    --${key}: ${value};`).join('\n')}\n}`;
 });
 return '/* Generated by sync-brand-consumer: Brand manifest roles + theme-tokens.json. */\n'+blocks.join('\n\n')+'\n';
}
export async function checkThemeColors(){
 const brandRoot=path.resolve(process.env.OXARA_BRAND_HOME||path.resolve(root,'../Oxara.Brand'));
 const manifest=JSON.parse(await readFile(path.join(brandRoot,'exports/document-template-web/manifest.json'),'utf8'));
 const expected=await renderThemeColors(manifest.consumerTheme),target=path.join(root,'features/base/theme-colors.css');
 if(await readFile(target,'utf8')!==expected)throw Error('Stale generated theme-colors.css; run sync-brand-consumer.');
 return expected;
}
